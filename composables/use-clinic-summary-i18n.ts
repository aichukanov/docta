import clinicCommonI18n from '~/i18n/clinic-common';
import clinicTypeI18n from '~/i18n/clinic-type';
import locationI18n from '~/i18n/location';
import { combineI18nMessages } from '~/i18n/utils';

/**
 * Общий словарь для шапки сводки клиники.
 *
 * Компонент самый тиражируемый на сайте: до трёх сводок на карточку и до
 * двадцати карточек на листинге — до шестидесяти экземпляров на страницу.
 *
 * Раньше слияние стояло прямо в `<script setup>` с комментарием «вынесено на
 * уровень модуля», и это было неправдой: любой top-level `const` внутри SFC
 * компилируется в тело `setup()` и выполняется на каждый экземпляр (проверено
 * компиляцией через @vue/compiler-sfc). То есть шестьдесят раз за рендер
 * склеивались три словаря на шесть локалей, и получалось шестьдесят разных
 * объектов с одинаковым содержимым.
 *
 * В браузере vue-i18n держит messages в обычном `ref`, поэтому каждая копия
 * обзаводилась своим набором реактивных прокси. Здесь объект вычисляется один
 * раз на модуль: Vue кэширует прокси по исходному объекту, так что и прокси, и
 * карта зависимостей становятся общими.
 *
 * Composer при этом всё равно свой на экземпляр — vue-i18n привязывает его
 * время жизни к компоненту, переиспользовать один на всех нельзя.
 *
 * Мутировать словарь через этот композер нельзя (mergeLocaleMessage /
 * setLocaleMessage): правка ушла бы во все сводки сразу.
 */
const messages = combineI18nMessages([
	clinicCommonI18n,
	clinicTypeI18n,
	locationI18n,
]);

export function useClinicSummaryI18n() {
	return useI18n({ useScope: 'local', messages });
}
