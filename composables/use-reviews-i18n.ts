import reviewsI18n from '~/i18n/reviews';
import { combineI18nMessages } from '~/i18n/utils';

/**
 * Общий словарь отзывов для всех компонентов раздела.
 *
 * Внутри `<script setup>` любой top-level `const` попадает в тело `setup()` и
 * пересоздаётся на каждый экземпляр — вынос строчки «на уровень модуля» внутри
 * SFC этого не меняет (проверено компиляцией через @vue/compiler-sfc). То есть
 * `combineI18nMessages([reviewsI18n])` в самом компоненте давал свою копию
 * словаря на каждый отзыв в списке, а восемь компонентов раздела давали восемь
 * разных объектов с одинаковым содержимым.
 *
 * В браузере vue-i18n хранит messages в обычном `ref` (в SSR — в `shallowRef`),
 * то есть объект становится глубоко реактивным, и на каждую копию заводится
 * свой набор прокси и своя карта зависимостей. Здесь объект вычисляется один
 * раз на модуль и разделяется всеми: Vue кэширует reactive-прокси по исходному
 * объекту, так что прокси и зависимости тоже становятся общими.
 *
 * Composer при этом всё равно свой на экземпляр — vue-i18n привязывает его
 * время жизни к компоненту и уничтожает при размонтировании, переиспользовать
 * один на всех нельзя.
 *
 * Мутировать словарь (mergeLocaleMessage/setLocaleMessage) через этот композер
 * нельзя: правка ушла бы во все компоненты раздела сразу.
 */
const messages = combineI18nMessages([reviewsI18n]);

export function useReviewsI18n() {
	return useI18n({ useScope: 'local', messages });
}
