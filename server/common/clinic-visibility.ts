/**
 * Публичная видимость клиники в одном месте.
 *
 * Клиника публична, когда она опубликована владельцем (`status = 'published'`)
 * И не скрыта администратором (`hidden = 0`). Скрытая клиника обязана исчезнуть
 * сразу из всех публичных выборок — листингов, карточек услуг/анализов/лекарств,
 * отзывов и sitemap, — а таких мест ~15 файлов. Забыть одно значит оставить
 * страницу в индексе, поэтому предикат собирается функцией, а не пишется руками;
 * `tests/unit/clinic-visibility.spec.ts` следит, чтобы литерал не вернулся.
 *
 * Результат обёрнут в скобки — предикат подставляется и в `ON`, и в `WHERE`
 * рядом с `OR`, где приоритет операторов иначе меняет смысл.
 *
 * @param alias Алиас таблицы `clinics` в запросе (или само имя таблицы).
 */
export function clinicIsPublicSql(alias = 'c'): string {
	return `(${alias}.status = 'published' AND ${alias}.hidden = 0)`;
}
