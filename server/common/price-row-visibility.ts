/**
 * Публичная видимость строки прайса клиники (`clinic_medical_services`,
 * `clinic_lab_tests`) в одном месте.
 *
 * Строка с `is_obsolete = 1` — позиция, которую клиника больше не публикует
 * в своём прайсе. Её не удаляют: остаются код, цена и история, а админка
 * продолжает её показывать. Из публичных выборок — карточек, листингов, счётчиков
 * клиник, ранжирования и sitemap — она исчезает. Таких мест около десятка, поэтому
 * предикат собирается функцией, как и `clinicIsPublicSql`.
 *
 * Результат обёрнут в скобки — предикат подставляется и в `ON`, и в `WHERE`.
 *
 * @param alias Алиас таблицы цен в запросе (или само имя таблицы).
 */
export function priceRowIsActiveSql(alias: string): string {
	return `(${alias}.is_obsolete = 0)`;
}
