// Коллация для текстового поиска по названиям.
//
// Колонки лежат в `utf8mb4_unicode_ci`, а она складывает только диакритику,
// которую разбирает NFD (š→s, č→c, ž→z, ć→c). Буквы с перечёркиванием —
// отдельные кодовые точки, и в ней они НЕ складываются: `đ`, `ł`, `ø`, `ð`, `ħ`.
// Для черногорской базы это не экзотика — на 2026-08-31 в локальной БД
// 154 услуги вида «Određivanje …», 83 врача (`Đorđević`, `Kaluđerović`),
// 13 анализов (`Gvožđe`), вещество `gvožđe`. Пользователь без сербской
// раскладки набирает `odredivanje` или `dordevic` и получает пустую выдачу.
//
// `utf8mb4_unicode_520_ci` (UCA 5.2) складывает их все и при этом ничего не
// теряет: сверено на 372 комбинациях (8 таблиц × колонки имён × 12 запросов) —
// потеряно 0 совпадений. Взята она, а не `utf8mb4_0900_ai_ci`: набор
// складываемых букв у них совпал один в один, но 0900 существует только
// с MySQL 8.0, а 520 — с 5.7, и версия прода не завязывается на этот код.
//
// НЕ складывается ни в той, ни в другой: `ß`→`ss`, `æ`→`ae`, `œ`→`oe`,
// турецкая `ı`→`i`. Клиентская подсветка обязана держать ровно этот же набор,
// иначе она красит совпадения, которых сервер не делал — см.
// `common/search-highlight.ts`.
export const SEARCH_COLLATION = 'utf8mb4_unicode_520_ci';

/** `колонка COLLATE … LIKE ?` — один плейсхолдер, порядок параметров не меняется. */
export const foldedLike = (column: string): string =>
	`${column} COLLATE ${SEARCH_COLLATION} LIKE ?`;

/**
 * `кол1 COLLATE … LIKE ? OR кол2 COLLATE … LIKE ? …` — по плейсхолдеру на
 * колонку, в том же порядке, что и переданный список.
 */
export const foldedLikeAny = (columns: string[]): string =>
	columns.map(foldedLike).join(' OR ');
